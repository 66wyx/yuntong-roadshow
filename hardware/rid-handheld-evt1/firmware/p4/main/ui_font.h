#ifndef UI_FONT_H
#define UI_FONT_H

#include <stddef.h>
#include <stdint.h>

typedef enum {
    UI_FONT_SMALL = 0,
    UI_FONT_MEDIUM,
    UI_FONT_LARGE,
    UI_FONT_COUNT,
} ui_font_id_t;

/* One anti-aliased glyph; pixels are 4-bit coverage, two per byte, high nibble first. */
typedef struct {
    uint32_t codepoint;
    uint32_t offset;   /* byte offset into the font bitmap */
    uint8_t advance;   /* pen advance in pixels */
    uint8_t width;
    uint8_t height;
    int8_t x_offset;   /* left edge relative to the pen position */
    int8_t y_offset;   /* top edge relative to the baseline; negative is above */
} ui_glyph_t;

typedef struct {
    const ui_glyph_t *glyphs;  /* sorted by codepoint */
    size_t glyph_count;
    const uint8_t *bitmap;
    uint8_t line_height;
    uint8_t ascent;
} ui_font_t;

/* Generated by tools/gen_ui_font.py into ui_font_data.c. */
extern const ui_font_t ui_fonts[UI_FONT_COUNT];

uint32_t ui_font_next_codepoint(const char **cursor);
const ui_glyph_t *ui_font_glyph(ui_font_id_t font, uint32_t codepoint);
const ui_glyph_t *ui_font_glyph_or_fallback(ui_font_id_t font,
                                            uint32_t codepoint);
int ui_font_text_width(ui_font_id_t font, const char *text);

#endif
