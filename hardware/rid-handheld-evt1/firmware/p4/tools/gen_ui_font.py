"""Generate main/ui_font_data.c: anti-aliased glyphs for every UI string.

The character set is collected from the string literals in main/rid_ui.c and
the digits/symbols that formatted values can produce, so adding UI text and
re-running this script can never leave a glyph out. `--check` fails if the
committed table is missing any character the UI needs.

Font: Noto Sans SC (SIL Open Font License 1.1). Pass --font to point at a
local copy, e.g. NotoSansSC-VF.ttf or NotoSansCJKsc-Regular.otf.

Requires Pillow.
"""

from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

PROJECT = Path(__file__).resolve().parents[1]
UI_SOURCES = (PROJECT / "main" / "rid_ui.c",)
OUTPUT = PROJECT / "main" / "ui_font_data.c"

# Received identities are arbitrary printable ASCII; formatted values add a few symbols.
FORMATTED = "".join(chr(code) for code in range(0x20, 0x7F)) + "°×…—"

# (name, pixel size, variable-font weight)
FONTS = (
    ("small", 11, 450),
    ("medium", 15, 600),
    ("large", 24, 600),
)
LARGE_CHARS = "0123456789+-.—°"

STRING_LITERAL = re.compile(r'"((?:[^"\\\n]|\\.)*)"')


def ui_characters() -> str:
    characters = set(FORMATTED)
    for source in UI_SOURCES:
        code = source.read_text(encoding="utf-8")
        code = re.sub(r"/\*.*?\*/", "", code, flags=re.S)
        code = re.sub(r"//[^\n]*", "", code)
        code = re.sub(r"^\s*#include[^\n]*", "", code, flags=re.M)
        for literal in STRING_LITERAL.findall(code):
            text = ast.literal_eval('"' + literal + '"')
            text = re.sub(r"%[-+ #0]*\d*(?:\.\d+)?(?:l|ll|z)?[a-zA-Z%]", "", text)
            characters.update(text)
    return "".join(sorted(c for c in characters if c.isprintable()))


def load_font(path: Path, size: int, weight: int) -> ImageFont.FreeTypeFont:
    font = ImageFont.truetype(str(path), size=size)
    try:
        axes = font.get_variation_axes()
    except (OSError, AttributeError):
        axes = []
    if axes:
        font.set_variation_by_axes([weight])
    return font


def render_glyph(font: ImageFont.FreeTypeFont, character: str):
    advance = max(1, int(round(font.getlength(character))))
    left, top, right, bottom = font.getbbox(character, anchor="ls")
    if right <= left or bottom <= top:
        return advance, 0, 0, 0, 0, b""
    width = right - left
    height = bottom - top
    image = Image.new("L", (width, height), 0)
    ImageDraw.Draw(image).text((-left, -top), character, font=font, fill=255, anchor="ls")
    levels = [min(15, (value + 8) // 17) for value in image.tobytes()]
    if len(levels) % 2:
        levels.append(0)
    packed = bytes((levels[i] << 4) | levels[i + 1] for i in range(0, len(levels), 2))
    return advance, width, height, left, top, packed


def build_tables(font_path: Path, characters: str) -> list[str]:
    lines = [
        "/* Generated by tools/gen_ui_font.py. Do not edit. */",
        "/* Glyphs: Noto Sans SC, SIL Open Font License 1.1. */",
        "#include \"ui_font.h\"",
        "",
    ]
    font_entries = []
    for name, size, weight in FONTS:
        font = load_font(font_path, size, weight)
        ascent, descent = font.getmetrics()
        wanted = LARGE_CHARS if name == "large" else characters
        wanted = "".join(sorted(set(wanted + "?")))
        bitmap = bytearray()
        lines.append(f"static const ui_glyph_t {name}_glyphs[] = {{")
        for character in wanted:
            advance, width, height, x_offset, y_offset, packed = render_glyph(
                font, character
            )
            codepoint = ord(character)
            comment = character if character not in "\\*/" else f"U+{codepoint:04X}"
            lines.append(
                f"    {{0x{codepoint:04X}u, {len(bitmap)}u, {advance}, {width}, "
                f"{height}, {x_offset}, {y_offset}}}, /* {comment} */"
            )
            bitmap.extend(packed)
        lines.append("};")
        lines.append("")
        lines.append(f"static const uint8_t {name}_bitmap[] = {{")
        for start in range(0, len(bitmap), 16):
            chunk = ", ".join(f"0x{b:02X}" for b in bitmap[start:start + 16])
            lines.append(f"    {chunk},")
        if not bitmap:
            lines.append("    0x00,")
        lines.append("};")
        lines.append("")
        font_entries.append((name, ascent + descent, ascent))

    lines.append("const ui_font_t ui_fonts[UI_FONT_COUNT] = {")
    for name, line_height, ascent in font_entries:
        lines.append(
            f"    [UI_FONT_{name.upper()}] = {{{name}_glyphs, "
            f"sizeof({name}_glyphs) / sizeof({name}_glyphs[0]), "
            f"{name}_bitmap, {line_height}, {ascent}}},"
        )
    lines.append("};")
    lines.append("")
    return lines


def committed_characters(name: str) -> set[str]:
    if not OUTPUT.exists():
        return set()
    code = OUTPUT.read_text(encoding="utf-8")
    block = code.split(f"static const ui_glyph_t {name}_glyphs[]", 1)
    if len(block) < 2:
        return set()
    body = block[1].split("};", 1)[0]
    return {chr(int(value, 16)) for value in re.findall(r"\{0x([0-9A-F]+)u,", body)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--font", type=Path, help="Noto Sans SC .ttf/.otf")
    parser.add_argument("--check", action="store_true",
                        help="verify the committed table covers the UI")
    args = parser.parse_args()

    characters = ui_characters()
    if args.check:
        missing = {
            name: sorted(set(characters if name != "large" else LARGE_CHARS)
                         - committed_characters(name))
            for name, _, _ in FONTS
        }
        failed = {name: chars for name, chars in missing.items() if chars}
        for name, chars in failed.items():
            print(f"ui_font_data.c {name} font is missing: {''.join(chars)}")
        if failed:
            return 1
        print(f"ui_font_data.c covers all {len(characters)} UI characters")
        return 0

    if not args.font:
        parser.error("--font is required to generate glyphs")
    OUTPUT.write_text("\n".join(build_tables(args.font, characters)),
                      encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT.relative_to(PROJECT)} ({len(characters)} characters)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
