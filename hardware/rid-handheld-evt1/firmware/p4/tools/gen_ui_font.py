"""Generate the C glyph table from the validated MicroPython UI font."""

from __future__ import annotations

import importlib.util
from pathlib import Path


PROJECT = Path(__file__).resolve().parents[1]
REPOSITORY = Path(__file__).resolve().parents[3]
SOURCE = REPOSITORY / "outputs" / "evt0-validation" / "ui_font.py"
OUTPUT = PROJECT / "main" / "ui_font_data.h"


def load_font():
    spec = importlib.util.spec_from_file_location("evt0_ui_font", SOURCE)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def emit_table(lines: list[str], name: str, table: dict) -> None:
    entries = sorted((ord(char), width, rows) for char, (width, rows) in table.items())
    for index, (_, _, rows) in enumerate(entries):
        values = ", ".join(f"0x{value:08X}u" for value in rows)
        lines.append(f"static const uint32_t {name}_rows_{index}[] = {{{values}}};")
    lines.append(f"static const ui_glyph_t {name}[] = {{")
    for index, (codepoint, width, rows) in enumerate(entries):
        lines.append(
            f"    {{0x{codepoint:06X}u, {width}, {len(rows)}, "
            f"{name}_rows_{index}}},"
        )
    lines.append("};")
    lines.append("")


def main() -> None:
    font = load_font()
    lines = [
        "/* Generated by tools/gen_ui_font.py. */",
        "#ifndef UI_FONT_DATA_H",
        "#define UI_FONT_DATA_H",
        "",
        "#include <stdint.h>",
        "",
        "#include \"ui_font.h\"",
        "",
        f"#define UI_SMALL_HEIGHT {font.SMALL_HEIGHT}",
        f"#define UI_BIG_HEIGHT {font.BIG_HEIGHT}",
        "",
    ]
    emit_table(lines, "ui_small_glyphs", font.SMALL)
    emit_table(lines, "ui_big_glyphs", font.BIG)
    lines.extend(
        [
            "#define UI_SMALL_GLYPH_COUNT "
            "(sizeof(ui_small_glyphs) / sizeof(ui_small_glyphs[0]))",
            "#define UI_BIG_GLYPH_COUNT "
            "(sizeof(ui_big_glyphs) / sizeof(ui_big_glyphs[0]))",
            "",
            "#endif",
            "",
        ]
    )
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUTPUT}")


if __name__ == "__main__":
    main()
